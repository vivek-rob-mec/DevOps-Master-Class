# Governance

Engineering owns resource metadata and technical action. Finance owns invoice reconciliation and accounting policy. Product owns value and demand decisions. The FinOps team owns allocation rules, shared-cost methodology and cadence. Track forecast error, unallocated percentage, commitment coverage, idle cost, optimization realized and cost per business unit.
