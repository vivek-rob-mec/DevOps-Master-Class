# Game-day method

Record hypothesis, blast radius, owner, abort signal, baseline, exact fault, timestamps, alerts, actions, customer impact, data loss, recovery checksum and follow-up owner. Start in an isolated environment. Stop immediately if blast radius escapes, observability is lost, backups are unverified or an on-call owner withdraws approval.
