# High-level design

Sensors remain replaceable. Events are normalized into a stable detection contract, enriched with workload and cloud identity, evaluated by versioned rules and routed by severity. Evidence storage is access-controlled and immutable. Response automation is gated by confidence, scope and rollback rather than alert severity alone.
