# LLM platform runbook

For quality regression, identify the exact model/prompt/embedding/vector release and stop promotion. For leakage, disable the tenant/source, revoke access, delete vectors/caches, preserve audit evidence and assess notification duties. For GPU saturation, shed low-priority traffic, reduce max tokens/batch and scale only within budget. Roll back the complete release unit and rerun safety plus retrieval evaluation.
