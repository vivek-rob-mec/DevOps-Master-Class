# Detection standard

Every rule needs hypothesis, data source, severity rationale, owner, fixture, expected match, negative test, false-positive guidance, runbook and review date. Measure precision, recall on replay data, alert volume, triage latency and response outcome. A detection that nobody owns is disabled debt, not coverage.
