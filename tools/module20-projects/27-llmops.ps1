# Threat model

Threats include prompt injection, indirect document injection, cross-tenant retrieval, model/data poisoning, unsafe tool invocation, sensitive prompt logging, vector inversion, model-weight theft, denial-of-wallet and unlicensed data/models. Controls include tenant filters, source/ACL projection, content quarantine, no tools by default, output/citation evaluation, redaction, quotas, immutable artifacts, isolated GPU nodes, egress policy, license review and human approval for consequential use.
