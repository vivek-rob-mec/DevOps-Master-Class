# High-level design

OpenCost provides near-real-time Kubernetes allocations while provider billing exports provide invoice truth. A normalization layer maps both to FOCUS-shaped dimensions. The model produces showback, budgets and unit economics; an action register records whether the business accepts, optimizes or investigates each variance.
