@app.get("/ready")
async def ready():
 try:
  async with pool.acquire() as connection:await connection.fetchval("SELECT 1")
  return {"status":"ready"}
 except Exception as error:raise HTTPException(503,"database unavailable") from error

@app.post("/api/orders",status_code=201)
