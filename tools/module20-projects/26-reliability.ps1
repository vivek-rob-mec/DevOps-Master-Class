# High-level design

The lab separates availability, durability and recoverability. Load establishes steady state; Toxiproxy and Chaos Mesh introduce controlled faults; SLIs quantify user impact; backup/restore and regional infrastructure prove recovery. Evidence is machine-scored against explicit objectives rather than declared successful by observation alone.
